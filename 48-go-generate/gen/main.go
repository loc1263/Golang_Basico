// Generador de código propio para el tema 48.
// Lee un CSV y escribe un archivo .go con constantes, un map de búsqueda y
// métodos. Lo invoca `go generate` a través de la directiva //go:generate
// que está en ../main.go (no se ejecuta directamente).
//
// Pasos típicos de un generador:
//  1. Leer la fuente de verdad (aquí un CSV; podría ser SQL, JSON, un .proto,
//     o el propio código Go analizado con go/parser o go/types).
//  2. Rellenar una plantilla con text/template.
//  3. Formatear el resultado con go/format (así el código generado pasa gofmt).
//  4. Escribir el archivo con el encabezado "Code generated ... DO NOT EDIT."
package main

import (
	"bytes"
	"encoding/csv"
	"flag"
	"go/format"
	"log"
	"os"
	"strings"
	"text/template"
)

type Pais struct {
	Codigo, Nombre, Moneda, Prefijo string
}

// El comentario "// Code generated ... DO NOT EDIT." con ese formato exacto
// es una convención reconocida por herramientas: linters y gopls lo tratan
// como generado, y GitHub lo colapsa en los diffs.
var plantilla = template.Must(template.New("paises").Parse(`// Code generated by gen/main.go from {{.Fuente}}; DO NOT EDIT.

package main

// CodigoPais es un código ISO 3166-1 alfa-2.
type CodigoPais string

const (
{{- range .Paises}}
	Pais{{.Codigo}} CodigoPais = "{{.Codigo}}" // {{.Nombre}}
{{- end}}
)

// InfoPais contiene los datos de un país.
type InfoPais struct {
	Nombre  string
	Moneda  string
	Prefijo string
}

var paises = map[CodigoPais]InfoPais{
{{- range .Paises}}
	Pais{{.Codigo}}: {Nombre: "{{.Nombre}}", Moneda: "{{.Moneda}}", Prefijo: "{{.Prefijo}}"},
{{- end}}
}

// TodosLosPaises devuelve los códigos en el orden del archivo fuente.
func TodosLosPaises() []CodigoPais {
	return []CodigoPais{ {{- range $i, $p := .Paises}}{{if $i}}, {{end}}Pais{{$p.Codigo}}{{end -}} }
}

// Info devuelve los datos del país y si el código existe.
func (c CodigoPais) Info() (InfoPais, bool) {
	p, ok := paises[c]
	return p, ok
}
`))

func main() {
	entrada := flag.String("entrada", "", "archivo CSV de origen")
	salida := flag.String("salida", "", "archivo .go a generar")
	flag.Parse()

	f, err := os.Open(*entrada)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	filas, err := csv.NewReader(f).ReadAll()
	if err != nil {
		log.Fatal(err)
	}

	var paises []Pais
	for _, fila := range filas[1:] { // saltar encabezado
		paises = append(paises, Pais{
			Codigo:  strings.ToUpper(fila[0]),
			Nombre:  fila[1],
			Moneda:  fila[2],
			Prefijo: fila[3],
		})
	}

	var buf bytes.Buffer
	err = plantilla.Execute(&buf, map[string]any{"Fuente": *entrada, "Paises": paises})
	if err != nil {
		log.Fatal(err)
	}
	codigo, err := format.Source(buf.Bytes()) // equivalente a gofmt
	if err != nil {
		// Si la plantilla produjo Go inválido, mostrarlo ayuda a depurar
		os.Stderr.Write(buf.Bytes())
		log.Fatal("el código generado no compila: ", err)
	}
	if err := os.WriteFile(*salida, codigo, 0o644); err != nil {
		log.Fatal(err)
	}
	// GOFILE y GOLINE los define go generate: indican qué directiva nos llamó
	log.Printf("generado %s (%d países) desde la directiva en %s:%s",
		*salida, len(paises), os.Getenv("GOFILE"), os.Getenv("GOLINE"))
}
